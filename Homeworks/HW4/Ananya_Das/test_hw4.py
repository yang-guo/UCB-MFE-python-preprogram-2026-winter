# Evidence helpers

def fmt(value):
    if isinstance(value, pd.Timestamp):
        return f"{value.date()} ({value.day_name()[:3]})"
    if isinstance(value, (bool, str)):
        return str(value)
    if isinstance(value, (int, float)):
        if abs(value - round(value)) < 1e-6:
            return f"{round(value):,}"
        if abs(value) >= 1000:
            return f"{value:,.4f}"
        return f"{value:.6g}"
    return str(value)


class Section:
    def __init__(self, test, registry, title, setup):
        self.test, self.rows = test, []
        registry.append((title, setup, self.rows))

    def check(self, item, by_hand, expected, actual):
        if isinstance(expected, (int, float)) and not isinstance(expected, bool):
            ok = math.isclose(expected, actual, rel_tol=1e-9, abs_tol=1e-6)
        else:
            ok = expected == actual
        self.rows.append((item, by_hand, fmt(expected), fmt(actual), "✅" if ok else "❌"))
        self.test.assertTrue(ok, f"{item}: expected {expected!r}, code gave {actual!r}")


def write_block(name, title, intro, sections):
    lines = [f"<!-- BEGIN {name} -->", f"# {title}", "", intro, ""]
    for section_title, setup, rows in sorted(sections):
        lines += [f"## {section_title}", "", setup, "",
                  "| Check | By hand | Expected | Code | OK |", "|---|---|---:|---:|:-:|"]
        lines += [f"| {item} | {hand} | {exp} | {got} | {ok} |" for item, hand, exp, got, ok in rows]
        lines.append("")
    total = sum(len(rows) for _, _, rows in sections)
    passed = sum(row[-1] == "✅" for _, _, rows in sections for row in rows)
    lines += [f"**{passed} of {total} checks match.**", f"<!-- END {name} -->"]
    block = "\n".join(lines)

    text = EVIDENCE_FILE.read_text() if EVIDENCE_FILE.exists() else ""
    if not text.startswith(HEADER.splitlines()[0]):
        text = HEADER
    pattern = re.compile(rf"<!-- BEGIN {name} -->.*?<!-- END {name} -->", re.S)
    if pattern.search(text):
        text = pattern.sub(lambda _: block, text)
    else:
        text = text.rstrip("\n") + "\n\n" + block
    EVIDENCE_FILE.write_text(text.rstrip("\n") + "\n")


